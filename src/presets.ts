import type { Instrument, Note } from './storage.ts'

interface Preset {
  name: string
  bpm: number
  drums: number[][]
  bars: Note[][]
}

type Phrase = [pitch: number, step: number, length: number][]

function bar(piano: Phrase, guitar: Phrase, bass: Phrase): Note[] {
  const parts: [Instrument, Phrase][] = [['piano', piano], ['guitar', guitar], ['bass', bass]]
  return parts.flatMap(([instrument, phrase]) =>
    phrase.map(([pitch, step, length]) => ({ instrument, pitch, step, length })),
  )
}

